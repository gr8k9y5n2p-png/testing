import type { FundCategory, FundEstimate, FundFamily } from "./types";
import { roundTo } from "./queries";

type SeedInput = {
  id: string;
  fundName: string;
  ticker: string;
  cusip: string;
  family: FundFamily;
  category: FundCategory;
  shareClass: string;
  nav: number;
  estimatedDistributionPctNav: number;
  publishedAt: string;
  asOfDate: string;
  distributionYear?: number;
};

function incomeWeight(category: FundCategory): number {
  switch (category) {
    case "Intermediate Core Bond":
    case "High Yield Bond":
      return 0.92;
    case "Muni National Intermediate":
      return 0.2;
    case "Moderate Allocation":
      return 0.42;
    default:
      return 0.18;
  }
}

function fund(input: SeedInput): FundEstimate {
  const distributionYear = input.distributionYear ?? 2026;
  const amount = roundTo(input.nav * (input.estimatedDistributionPctNav / 100), 4);
  const ordinaryWeight = incomeWeight(input.category);
  const estimatedOrdinaryIncome = roundTo(amount * ordinaryWeight, 4);
  const estimatedCapitalGains = roundTo(amount - estimatedOrdinaryIncome, 4);

  return {
    ...input,
    distributionYear,
    estimatedDistributionAmount: amount,
    estimatedOrdinaryIncome,
    estimatedCapitalGains,
  };
}

